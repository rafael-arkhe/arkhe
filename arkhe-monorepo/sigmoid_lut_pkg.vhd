package body sigmoid_lut_pkg is

    function sigmoid_lut_lookup(x : real) return std_logic_vector is
        variable idx : integer range 0 to 255;
        variable x_clamped : real;
    begin
        if x <= SIGMOID_X_MIN then
            return x"00000001";  -- Aproximadamente 0
        elsif x >= SIGMOID_X_MAX then
            return x"01000000";  -- 1.0 em Q8.24
        else
            idx := integer((x - SIGMOID_X_MIN) / SIGMOID_STEP);
            if idx < 0 then idx := 0; end if;
            if idx > 255 then idx := 255; end if;
            return SIGMOID_LUT(idx);
        end if;
    end function;

    function sigmoid_lut_lookup(x : signed(31 downto 0)) return signed is
        variable x_real : real;
    begin
        -- Converter Q8.24 para real
        x_real := real(to_integer(x)) / real(2**24);
        return signed(sigmoid_lut_lookup(x_real));
    end function;

end package body;